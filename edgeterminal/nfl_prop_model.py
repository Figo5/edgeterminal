CUTOFF = (2026, 3)
DIRECTORY = lab.ROOT / "data/research/nfl_prop_model/v2"
EXTRA_FEATURES = ("opportunity_change", "stat_change", "efficiency_last3",
                  "efficiency_last5", "usage_projection", "opportunity_ratio",
                  "log_prior_games")
FEATURES = tuple(lab.FEATURES) + EXTRA_FEATURES
FAMILIES = ("baseline", "ridge_role", "boosted_role", "median_role")
PARAMETERS = {
    "version": VERSION, "training_cutoff": list(CUTOFF),
    "features": list(FEATURES), "selection": "top-five-confidence-v1",
    "families": list(FAMILIES), "ridge_alpha": 100.,
    "boosting": {"iterations": 90, "leaves": 15, "min_leaf": 40,
                 "l2": 10., "learning_rate": .06, "random_state": 13},
    "development": "2024 weeks 1-9; fitted before 2024",
    "calibration": "2024 weeks 10-18; fitted before week 10",
    "calibration_method_selection": "2024 weeks 15-18; residuals weeks 10-14",
    "acceptance": "2025; per-market baseline fallback on MAE regression",
    "residual_minimum": 100, "local_minimum": 60,
    "local_shrinkage": 100., "tail_pseudocount_each_side": .5,
    "thresholds": "half-integers around previous-three-game average",
    "counts": "nonnegative integer outcomes with explicit push mass",
}
PARAMETER_FINGERPRINT = hashlib.sha256(json.dumps(
    PARAMETERS, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
# This pin is generated by the explicit offline build and reviewed with code.
